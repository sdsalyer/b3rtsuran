void write_layer_text(uint16_t state, uint16_t layer, const char *text) {
    bool is_active = layer_state_cmp(state, layer);

    oled_write_P(is_active ? PSTR(">") : PSTR(" "), false);

    oled_write_P(text, false);

    oled_write_P(is_active ? PSTR("<") : PSTR(" "), false);

    oled_write_P(PSTR("\n"), false);
}

